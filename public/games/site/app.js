/* Kids Games Player website: game list, filters, download sizes, GitHub links.
   Data comes from site/catalog.js (generated by tools/build_site.py). */
(function () {
  'use strict';
  var KGP = window.KGP || { games: [], collections: [], packs: [] };

  // ---------------------------------------------------------------- GitHub links
  // On <user>.github.io/<repo>/ the repo is https://github.com/<user>/<repo>; a non-empty
  // <meta name="kgp-repo"> wins. Elsewhere (local preview) links stay relative.
  function repoUrl() {
    var meta = document.querySelector('meta[name="kgp-repo"]');
    if (meta && meta.content) return meta.content.replace(/\/+$/, '');
    var host = /^([a-z0-9-]+)\.github\.io$/i.exec(location.hostname);
    if (!host) return null;
    var first = location.pathname.split('/').filter(Boolean)[0];
    var repo = first && !/\.html?$/i.test(first) ? first : host[1] + '.github.io';
    return 'https://github.com/' + host[1] + '/' + repo;
  }
  var repo = repoUrl();
  Array.prototype.forEach.call(document.querySelectorAll('[data-gh]'), function (a) {
    var path = a.getAttribute('data-gh');
    if (repo) {
      var kind = a.hasAttribute('data-gh-tree') ? '/tree/HEAD/' : '/blob/HEAD/';
      a.href = repo + (path ? kind + path.split('/').map(encodeURIComponent).join('/') : '');
      a.hidden = false;
    } else if (!path) {
      a.hidden = true;
      var li = a.closest('li');
      if (li) li.hidden = true;
    }
  });

  // ---------------------------------------------------------------- helpers
  function size(bytes) {
    if (!bytes) return '';
    var mb = bytes / 1048576;
    if (mb >= 1) return mb.toFixed(1).replace('.', ',') + ' MB';
    return Math.max(1, Math.round(bytes / 1024)) + ' KB';
  }
  function el(tag, attrs, children) {
    var e = document.createElement(tag);
    if (attrs) Object.keys(attrs).forEach(function (k) {
      if (k === 'text') e.textContent = attrs[k];
      else if (k === 'className') e.className = attrs[k];
      else e.setAttribute(k, attrs[k]);
    });
    (children || []).forEach(function (c) { if (c) e.appendChild(c); });
    return e;
  }
  function fold(s) {
    return String(s).toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '').replace(/đ/g, 'd');
  }
  function fileUrl(path) { return path.split('/').map(encodeURIComponent).join('/'); }

  // ---------------------------------------------------------------- downloads
  var apk = KGP.apk;
  if (apk && document.getElementById('apk-ver')) {
    Array.prototype.forEach.call(document.querySelectorAll('[data-apk]'), function (a) { a.href = fileUrl(apk.file); });
    document.getElementById('apk-ver').textContent = apk.version;
    document.getElementById('apk-size').textContent = '(' + size(apk.bytes) + ')';
    document.getElementById('apk-sha').textContent = apk.sha256;
    document.getElementById('apk-cert').textContent = apk.certSha256;
    var heroMeta = document.getElementById('hero-meta');
    heroMeta.textContent = 'Bản ' + apk.version + ' · ' + size(apk.bytes) + ' · Android 8 trở lên · Có giọng đọc tiếng Việt offline';
  }
  var list = document.getElementById('pack-list');
  if (list && KGP.packs && KGP.packs.length) {
    list.textContent = '';
    KGP.packs.forEach(function (p) {
      list.appendChild(el('li', null, [
        el('a', { href: fileUrl(p.file), download: '', text: p.name }),
        el('span', { className: 'meta', text: ' · ' + p.count + ' game · ' + size(p.bytes) })
      ]));
    });
  }

  // ---------------------------------------------------------------- copy buttons (guide page)
  Array.prototype.forEach.call(document.querySelectorAll('.prompt .copy'), function (btn) {
    btn.addEventListener('click', function () {
      var text = btn.closest('.prompt').querySelector('code').textContent;
      function done(ok) {
        btn.textContent = ok ? 'Đã chép ✓' : 'Hãy bôi đen để chép';
        setTimeout(function () { btn.textContent = 'Sao chép'; }, 1800);
      }
      function legacyCopy() {
        var ta = el('textarea');
        ta.value = text;
        ta.setAttribute('readonly', '');
        ta.style.cssText = 'position:fixed;top:0;left:0;opacity:0';
        document.body.appendChild(ta);
        ta.select();
        var ok = false;
        try { ok = document.execCommand('copy'); } catch (e) { ok = false; }
        ta.remove();
        return ok;
      }
      if (navigator.clipboard && window.isSecureContext) {
        navigator.clipboard.writeText(text).then(function () { done(true); }, function () { done(legacyCopy()); });
      } else {
        done(legacyCopy());
      }
    });
  });

  // ---------------------------------------------------------------- game list
  var grid = document.getElementById('grid');
  if (!grid) return;
  var games = KGP.games || [];
  var names = {};
  (KGP.collections || []).forEach(function (c) { names[c.id] = c; });
  var state = { col: 'all', a8: false, voice: false, q: '' };
  var count = document.getElementById('count');
  var chips = document.getElementById('chips');

  function card(g) {
    var icon = g.icon
      ? el('img', { className: 'icon', src: fileUrl(g.icon), alt: '', width: '84', height: '84', loading: 'lazy', decoding: 'async' })
      : el('div', { className: 'icon ph', 'aria-hidden': 'true', text: '🎲' });
    var tags = el('ul', { className: 'tags' });
    tags.appendChild(el('li', { text: names[g.collection] ? names[g.collection].name : g.collection }));
    if (g.ages) tags.appendChild(el('li', { text: g.ages + ' tuổi' }));
    if (g.voice) tags.appendChild(el('li', { text: '🔊 Có lời đọc' }));
    if (g.android8) tags.appendChild(el('li', { className: 'a8', text: 'Android 8' }));
    if (g.template) tags.appendChild(el('li', { text: 'Khuôn mẫu' }));
    var play = el('a', {
      className: 'btn btn-yellow btn-sm', href: 'play.html?g=' + encodeURIComponent(g.slug),
      target: '_blank', rel: 'noopener', text: '▶ Chơi', 'aria-label': 'Chơi ' + g.title
    });
    var dl = el('a', {
      className: 'btn btn-ghost btn-sm', href: fileUrl(g.zip), download: '',
      text: '⬇ ' + size(g.zipBytes), 'aria-label': 'Tải ' + g.title + ' (' + size(g.zipBytes) + ')'
    });
    return el('article', { className: 'card' }, [
      icon,
      el('div', null, [el('h3', { text: g.title }), el('p', { text: g.blurb }), tags]),
      el('div', { className: 'actions' }, [play, dl])
    ]);
  }
  games.forEach(function (g) { g._el = card(g); g._key = fold(g.title + ' ' + g.blurb); });

  function matches(g, col) {
    if (col !== 'all' && g.collection !== col) return false;
    if (state.a8 && !g.android8) return false;
    if (state.voice && !g.voice) return false;
    if (state.q && g._key.indexOf(state.q) < 0) return false;
    return true;
  }

  function renderChips() {
    chips.textContent = '';
    var ids = ['all'].concat((KGP.collections || []).map(function (c) { return c.id; }));
    ids.forEach(function (id) {
      var n = games.filter(function (g) { return matches(g, id); }).length;
      if (id !== 'all' && n === 0 && state.col !== id) return;
      var label = id === 'all' ? 'Tất cả' : names[id].name;
      var b = el('button', { type: 'button', className: 'chip', 'aria-pressed': String(state.col === id) }, [
        document.createTextNode(label), el('span', { className: 'n', text: ' ' + n })
      ]);
      if (id !== 'all') b.title = names[id].note;
      b.addEventListener('click', function () { state.col = id; render(); });
      chips.appendChild(b);
    });
  }

  function render() {
    renderChips();
    grid.textContent = '';
    var shown = games.filter(function (g) { return matches(g, state.col); });
    shown.forEach(function (g) { grid.appendChild(g._el); });
    if (!shown.length) grid.appendChild(el('p', { className: 'empty', text: 'Không có game nào khớp. Thử bỏ bớt bộ lọc.' }));
    var playable = games.filter(function (g) { return !g.template; }).length;
    count.textContent = shown.length === games.length
      ? playable + ' trò chơi và 1 khuôn mẫu để làm game mới.'
      : 'Đang hiện ' + shown.length + ' / ' + games.length + '.';
  }

  document.getElementById('f-a8').addEventListener('change', function (e) { state.a8 = e.target.checked; render(); });
  document.getElementById('f-voice').addEventListener('change', function (e) { state.voice = e.target.checked; render(); });
  document.getElementById('q').addEventListener('input', function (e) { state.q = fold(e.target.value.trim()); render(); });
  render();
})();
